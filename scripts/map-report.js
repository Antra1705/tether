#!/usr/bin/env node
// Mapping-fidelity measurement (milestone 8, AC-6).
//
//   npm run map-report
//
// Compiles each benchmark, the optimisation fixture and the sieve fixture at
// -O0 and -O1 and writes the retention figures to docs/fidelity.md.

import { readFileSync, writeFileSync } from 'node:fs';
import { compile } from '../src/compiler.js';
import { mappingRetention } from '../src/optimize.js';

const FILES = [
  'examples/fib.tth', 'examples/primes.tth', 'examples/collatz.tth', 'examples/fizzbuzz.tth',
  'test/fixtures/optimisable.tth', 'test/fixtures/sieve.tth',
];

const rows = [];
for (const file of FILES) {
  const text = readFileSync(file, 'utf8');
  const levels = [false, true].map((optimise) => {
    const r = compile(file, text, { jsFile: 'x.js', optimise });
    return { ...mappingRetention(r.ast, r.table), ...(r.optimisation ?? { folded: 0, propagated: 0, removed: 0 }) };
  });
  rows.push({ file, o0: levels[0], o1: levels[1] });
}

const pct = (x) => `${(x * 100).toFixed(1)}%`;
const count = (n, one, many = `${one}s`) => `${n} ${n === 1 ? one : many}`;
const row = (path) => rows.find((r) => r.file === path);
const opt = row('test/fixtures/optimisable.tth');
const sieve = row('test/fixtures/sieve.tth');
let md = `# Mapping fidelity at -O0 and -O1 (milestone 8)

Generated by \`npm run map-report\`. Do not edit by hand.

"Retained" is the share of source statements whose first token still has a
mapping in the generated source map, which is what a debugger needs to stop on
that statement. It is measured by \`--map-report\` (FR-O3).

Mappings are recorded at the start of every statement, every identifier,
every expression and every binary operator, so the mapping count is much
larger than the statement count.

| Program | Statements | Retained at -O0 | Retained at -O1 | Mappings -O0 → -O1 | Folded | Propagated | Statements removed |
|---------|-----------:|----------------:|----------------:|-------------------:|-------:|-----------:|-------------------:|
`;
for (const { file, o0, o1 } of rows) {
  md += `| \`${file}\` | ${o0.statements} | ${o0.kept} (${pct(o0.ratio)}) | ${o1.kept} (${pct(o1.ratio)}) | ${o0.mappings} → ${o1.mappings} | ${o1.folded} | ${o1.propagated} | ${o1.removed} |\n`;
}
const bench = rows.filter((r) => r.file.startsWith('examples/'));
const allKept = bench.every((r) => r.o1.ratio === 1);
const name = (r) => `\`${r.file.split('/').pop()}\``;
const touched = bench.filter((r) => r.o1.folded + r.o1.propagated + r.o1.removed > 0);
const untouched = bench.filter((r) => !touched.includes(r));
const describe = (r) => `${name(r)} (${r.o1.folded} folded, ${r.o1.propagated} propagated, ${r.o1.removed} removed)`;
md += `
## Findings

- At -O0 every source statement keeps a mapping, in every program (FR-X4).
- ${allKept
    ? `The four benchmarks keep every statement mapping at -O1. They contain almost nothing to optimise: ${
      touched.length ? `only ${touched.map(describe).join(' and ')} change${touched.length === 1 ? 's' : ''}` : 'nothing changes'}${
      untouched.length ? `, and the JavaScript for ${untouched.map(name).join(', ')} is identical at both levels` : ''}. Their zero loss is therefore mostly by construction, not a measured property of the optimiser.`
    : 'Some benchmarks lose mappings at -O1; see the table.'}
- \`test/fixtures/optimisable.tth\` is written to exercise the optimiser: constant
  arithmetic, string concatenation, \`if (false)\`, \`while (false)\`, a constant
  \`&&\`, and a statement after \`return\`. At -O1, ${count(opt.o1.folded, 'expression')} folded,
  ${count(opt.o1.propagated, 'constant read')} propagated and ${count(opt.o1.removed, 'statement')} removed, and statement retention falls from
  ${pct(opt.o0.ratio)} to ${pct(opt.o1.ratio)}.
  The program still prints exactly the same output (checked by \`test/optimize.test.js\`).
- \`test/fixtures/sieve.tth\` uses arrays, \`break\` and \`continue\`. At -O1 its
  constant \`limit\` is propagated into ${count(sieve.o1.propagated, 'read')}; ${count(sieve.o1.folded, 'expression')} folded and
  ${count(sieve.o1.removed, 'statement')} removed, and statement retention is ${pct(sieve.o1.ratio)}.
- Folding loses no statement mappings by itself: a folded expression takes the
  span of the whole expression it replaces (FR-O2). Constant propagation loses
  none either: the propagated value takes the identifier's span, and the
  \`let\` that declared the constant is kept, so a debugger can still show it. Mappings are lost only for
  removed statements. Most of them could never run (a dead branch, a
  \`while (false)\` body, code after \`return\`), so no reachable breakpoint is
  lost there. The exception is an \`if\` whose condition folds to a constant:
  the \`if\` itself is removed, so a breakpoint on its line no longer stops and
  has to be set on a statement inside the branch that is kept.
`;
writeFileSync('docs/fidelity.md', md);
console.log(md);
